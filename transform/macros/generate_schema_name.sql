-- Override dbt default: use custom schema name directly instead of
-- prepending the target schema (which would produce RAW_SILVER, RAW_GOLD).
{% macro generate_schema_name(custom_schema_name, node) -%}
    {%- set default_schema = target.schema -%}
    {%- if custom_schema_name is none -%}
        {{ default_schema }}
    {%- else -%}
        {{ custom_schema_name | trim }}
    {%- endif -%}
{%- endmacro %}
